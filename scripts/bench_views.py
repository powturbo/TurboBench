#!/usr/bin/env python3
"""Multi-page TurboBench Markdown views (table first, same graphs on each page).

Reads a report (for example turbobench_/micro.md) and writes one file per sort
column. Every page has: preamble, one table, then the same PNG charts.

* ``micro.md`` — default view, C Size order as in the source (TurboBench
  history). The C Size header is not a link.
* ``micro_ratio.md``, ``micro_CMBs.md``, ``micro_DMBs.md``, … — same table
  sorted best-first on that column. Column headers link to the other views;
  C Size always links back to ``micro.md``.

    ./turbobench data@MICRO.tbb -p4          # → data.md (TurboBench raw table)
    python3 scripts/bench_views.py data.md --stem micro --out-dir turbobench_/

Or use scripts/enhance_bench_md.sh (see scripts/README.md).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

_LATEX = re.compile(r"\$\\color\{[^{}]*\}\{\\textbf\{(.*?)\}\}\$")
_LINK = re.compile(r"\[([^\]]*)\]\(([^)]*)\)")
_MEDAL = re.compile("[🏆🥇🥈🥉👑]")
_SEP_CELL = re.compile(r":?-{3,}:?")
_CHART_IMG = re.compile(r"^!\[[^\]]*\]\(charts/[^)]+\)\s*$")
_GEN_MARKER = "<!-- generated by scripts/bench_views.py -->"
_CAP_SCATTER = "Each point is one codec level."
_CAP_BARS = "Fastest decompression at the top."

FASTER = {"c mb/s", "d mb/s"}
DCAT_ORDER = {"pico": 0, "tiny": 1, "small": 2, "medium": 3, "large": 4}
# Filename suffix per column (None => default ``{stem}.md``, always C Size).
VIEW_SUFFIX: dict[str, str | None] = {
    "c size": None,
    "ratio%": "ratio",
    "ratio": "ratio",
    "c mb/s": "CMBs",
    "d mb/s": "DMBs",
    "rank": "Rank",
    "c mem": "CMem",
    "c stack": "CStack",
    "d mem": "DMem",
    "d stack": "DStack",
    "name": "Name",
    "file": "File",
    "d cat": "DCat",
}
# Distinct hues. Yellow is darkened so it stays visible on a white background.
PALETTE = [
    "#0072B2", "#E69F00", "#009E73", "#D55E00", "#CC79A7",
    "#56B4E9", "#C4A000", "#882255", "#44AA99", "#332288",
    "#117733", "#AA4499", "#999933", "#661100", "#6699CC",
    "#000000",
]


def plain(cell: str) -> str:
    text = _LATEX.sub(r"\1", cell.strip())
    text = _LINK.sub(r"\1", text)
    text = text.replace("\\_", "_")
    text = _MEDAL.sub("", text)
    return text.strip()


def numeric(cell: str):
    token = plain(cell).replace("%", "").replace(",", "").replace(" ", "")
    if not token:
        return None
    try:
        return float(token)
    except ValueError:
        return None


def split_row(line: str) -> list[str]:
    text = line.strip()
    if text.startswith("|"):
        text = text[1:]
    if text.endswith("|"):
        text = text[:-1]
    return [cell.strip() for cell in text.split("|")]


def header_label(cell: str) -> str:
    """Strip navigation markup when re-processing an already generated report."""
    text = cell.strip()
    bold = re.match(r"\*\*(.+?)\*\*", text)
    if bold:
        return bold.group(1)
    linked = re.match(r"\[([^\]]+)\]\([^)]+\)", text)
    if linked:
        return linked.group(1)
    return text


def is_separator(line: str) -> bool:
    if "|" not in line:
        return False
    cells = split_row(line)
    return len(cells) >= 2 and all(_SEP_CELL.fullmatch(cell.replace(" ", "")) for cell in cells)


def strip_bench_views_artifacts(text: str) -> str:
    """Drop chart embeds from a previous run so graphs are not appended twice."""
    kept: list[str] = []
    for line in text.splitlines():
        s = line.strip()
        if s == _GEN_MARKER:
            continue
        if _CHART_IMG.match(s):
            continue
        if s.startswith(_CAP_SCATTER) or s.startswith(_CAP_BARS):
            continue
        kept.append(line)
    return "\n".join(kept)


def parse_blocks(text: str):
    lines = text.splitlines()
    blocks = []
    start = 0
    i = 0
    while i < len(lines) - 1:
        if lines[i].lstrip().startswith("|") and is_separator(lines[i + 1]):
            header = [header_label(c) for c in split_row(lines[i])]
            rows = []
            j = i + 2
            while j < len(lines) and lines[j].lstrip().startswith("|"):
                row = split_row(lines[j])
                if len(row) < len(header):
                    row = row + [""] * (len(header) - len(row))
                rows.append(row[: len(header)])
                j += 1
            blocks.append((lines[start:i], header, rows))
            start = j
            i = j
        else:
            i += 1
    return blocks, lines[start:]


def is_numeric_column(rows: list[list[str]], index: int) -> bool:
    if not rows:
        return False
    found = 0
    for row in rows:
        if index < len(row) and numeric(row[index]) is not None:
            found += 1
    return found >= max(1, int(0.6 * len(rows)))


def column_meta(header: list[str], rows: list[list[str]]) -> list[dict]:
    meta = []
    for i, name in enumerate(header):
        key = name.lower()
        dcat = key == "d cat"
        textual = not dcat and not is_numeric_column(rows, i)
        descending = key in FASTER
        if dcat:
            phrase = "smallest class first"
        elif descending:
            phrase = "fastest first"
        elif key == "rank":
            phrase = "best first"
        elif textual:
            phrase = "A to Z"
        else:
            phrase = "smallest first"
        meta.append({
            "index": i,
            "header": name,
            "dcat": dcat,
            "textual": textual,
            "descending": descending,
            "phrase": phrase,
        })
    return meta


def sort_rows(rows: list[list[str]], col: dict) -> list[list[str]]:
    index = col["index"]

    def key(item):
        pos, row = item
        cell = row[index] if index < len(row) else ""
        if col["dcat"]:
            label = plain(cell).lower()
            return (DCAT_ORDER.get(label, 50), label, pos)
        value = numeric(cell)
        if value is None:
            return (1, plain(cell).lower(), pos)
        return (0, -value if col["descending"] else value, pos)

    return [row for _, row in sorted(enumerate(rows), key=key)]


def block_prefix(block_index: int, multi: bool) -> str:
    return f"b{block_index}_" if multi else ""


def view_basename(stem: str, prefix: str, column_header: str) -> str:
    key = column_header.lower()
    if key == "c size":
        return f"{prefix}{stem}.md"
    suffix = VIEW_SUFFIX.get(key)
    if suffix is None:
        suffix = re.sub(r"[^A-Za-z0-9]+", "", column_header) or "view"
    return f"{prefix}{stem}_{suffix}.md"


def column_view_links(stem: str, prefix: str, columns: list[dict]) -> list[str]:
    return [view_basename(stem, prefix, col["header"]) for col in columns]


def find_col(header: list[str], names: tuple[str, ...]):
    lowered = [name.lower() for name in header]
    for name in names:
        if name in lowered:
            return lowered.index(name)
    return None


def family_of(name: str) -> str:
    parts = name.split()
    if len(parts) >= 2 and re.fullmatch(r"\d+(?:\.\d+)?", parts[-1]):
        return " ".join(parts[:-1])
    return name


def is_memcpy(name: str, ratio) -> bool:
    return name.lower().startswith("memcpy") or (ratio is not None and ratio >= 99.5)


def section_title(preamble: list[str]) -> str:
    for line in reversed(preamble):
        if line.lstrip().startswith("#"):
            return line.lstrip("#").strip()
    return "TurboBench"


def pareto(points: list[tuple]) -> list[tuple]:
    """Keep points no other point dominates (higher speed and lower ratio)."""
    kept = []
    for i, point in enumerate(points):
        speed, ratio = point[0], point[1]
        dominated = False
        for j, other in enumerate(points):
            if i == j:
                continue
            if other[0] >= speed and other[1] <= ratio and (other[0] > speed or other[1] < ratio):
                dominated = True
                break
        if not dominated:
            kept.append(point)
    kept.sort(key=lambda point: (point[0], point[1]))
    return kept


def _points(rows, speed_i, ratio_i, name_i):
    points = []
    omitted = None
    for row in rows:
        speed = numeric(row[speed_i]) if speed_i is not None else None
        ratio = numeric(row[ratio_i]) if ratio_i is not None else None
        name = plain(row[name_i]) if name_i is not None and name_i < len(row) else ""
        if speed is None or ratio is None or speed <= 0:
            continue
        if is_memcpy(name, ratio):
            omitted = (speed, ratio, name)
            continue
        points.append((speed, ratio, name))
    return points, omitted


def _colors(names: list[str]) -> dict[str, str]:
    families = sorted(set(names))
    return {family: PALETTE[i % len(PALETTE)] for i, family in enumerate(families)}


def _save(fig, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150, bbox_inches="tight", facecolor="white")
    import matplotlib.pyplot as plt
    plt.close(fig)


def write_scatter(path: Path, title: str, rows, header) -> str | None:
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    try:
        from adjustText import adjust_text
    except ImportError:
        adjust_text = None

    name_i = find_col(header, ("name",))
    ratio_i = find_col(header, ("ratio%", "ratio"))
    comp_i = find_col(header, ("c mb/s",))
    decomp_i = find_col(header, ("d mb/s",))
    if name_i is None or ratio_i is None or (comp_i is None and decomp_i is None):
        return None

    series = []
    if comp_i is not None:
        series.append(("Compression speed vs ratio", comp_i, "compression MB/s   (faster →)"))
    if decomp_i is not None:
        series.append(("Decompression speed vs ratio", decomp_i, "decompression MB/s   (faster →)"))

    prepared = []
    families = []
    omitted_name = None
    for label, speed_i, xlabel in series:
        points, omitted = _points(rows, speed_i, ratio_i, name_i)
        if omitted and omitted_name is None:
            omitted_name = omitted[2]
        families.extend(family_of(point[2]) for point in points)
        prepared.append((label, xlabel, points, pareto(points)))
    if not any(item[2] for item in prepared):
        return None
    colors = _colors(families)

    fig, axes = plt.subplots(len(prepared), 1, figsize=(11.2, 6.8 * len(prepared)), squeeze=False)
    for ax, (label, xlabel, points, front) in zip(axes[:, 0], prepared):
        front_ids = {(point[0], point[1], point[2]) for point in front}
        span = max(point[0] for point in points) / min(point[0] for point in points)
        log_x = span >= 12
        for speed, ratio, name in points:
            on_front = (speed, ratio, name) in front_ids
            ax.scatter(
                [speed], [ratio],
                s=78 if on_front else 42,
                c=[colors[family_of(name)]],
                edgecolors="#222",
                linewidths=0.9 if on_front else 0.4,
                zorder=3 if on_front else 2,
            )
        if len(front) >= 2:
            ax.plot([point[0] for point in front], [point[1] for point in front], color="#222", lw=1.3, zorder=1)
        ratios = [point[1] for point in points]
        speeds = [point[0] for point in points]
        pad = max(1.5, (max(ratios) - min(ratios)) * 0.12)
        ax.set_ylim(min(ratios) - pad, max(ratios) + pad)
        if log_x:
            ax.set_xscale("log")
            ax.set_xlim(min(speeds) / 1.9, max(speeds) * 2.6)
            xlabel = xlabel.replace("(faster →)", "(log, faster →)")
        else:
            ax.set_xlim(min(speeds) - span_pad(speeds) * 2, max(speeds) + span_pad(speeds) * 3.5)
        ax.set_title(label)
        ax.set_xlabel(xlabel)
        ax.set_ylabel("ratio %   (lower compresses more)")
        ax.grid(True, which="both", ls=":", color="#d0d7de")
        ax.set_axisbelow(True)
        # Label the Pareto front only. The bar chart names every codec, and a
        # full set of labels on this cloud collides once GitHub scales the image.
        texts = [
            ax.text(speed, ratio, name, fontsize=11, ha="center", va="bottom", color="#222")
            for speed, ratio, name in points
            if (speed, ratio, name) in front_ids
        ]
        if adjust_text is not None and texts:
            adjust_text(
                texts, ax=ax,
                arrowprops=dict(arrowstyle="-", color="#888", lw=0.6),
                ensure_inside_axes=True,
                expand=(1.15, 1.3),
                force_text=(0.6, 0.9),
                force_explode=(0.5, 1.0),
                min_arrow_len=8,
                time_lim=4,
            )
    handles = [
        Line2D([0], [0], marker="o", linestyle="", markerfacecolor=colors[family],
               markeredgecolor="#222", markersize=8, label=family)
        for family in colors
    ]
    fig.suptitle(title, fontsize=12)
    # Legend sits in a reserved band under both panels, clear of the axes.
    fig.tight_layout(rect=(0.0, 0.07, 1.0, 0.96))
    fig.legend(
        handles=handles, loc="lower center", bbox_to_anchor=(0.5, 0.0),
        ncol=7, frameon=False, borderaxespad=0,
    )
    _save(fig, path)
    return omitted_name


def span_pad(values: list[float]) -> float:
    return max(1.0, (max(values) - min(values)) * 0.08)


def write_bars(path: Path, title: str, rows, header) -> str | None:
    import matplotlib.pyplot as plt

    name_i = find_col(header, ("name",))
    ratio_i = find_col(header, ("ratio%", "ratio"))
    decomp_i = find_col(header, ("d mb/s",))
    if name_i is None or decomp_i is None:
        return None
    points, omitted = _points(rows, decomp_i, ratio_i if ratio_i is not None else decomp_i, name_i)
    if ratio_i is None:
        points = []
        omitted = None
        for row in rows:
            speed = numeric(row[decomp_i])
            name = plain(row[name_i])
            if speed is None or speed <= 0:
                continue
            if is_memcpy(name, None):
                omitted = (speed, 0, name)
                continue
            points.append((speed, 0, name))
    if not points:
        return None
    front_ids = {(point[0], point[1], point[2]) for point in pareto(points)} if ratio_i is not None else set()
    points = sorted(points, key=lambda point: point[0])
    colors = _colors([family_of(point[2]) for point in points])
    labels = []
    for speed, ratio, name in points:
        if ratio_i is None:
            labels.append(name)
        else:
            labels.append(f"{name}    {ratio:.2f}%")

    fig_h = 0.38 * len(points) + 1.15
    fig, ax = plt.subplots(figsize=(10.2, fig_h))
    positions = list(range(len(points)))
    values = [point[0] for point in points]
    ax.barh(
        positions, values,
        color=[colors[family_of(point[2])] for point in points],
        edgecolor="#222", linewidth=0.4, height=0.72, zorder=2,
    )
    ax.set_yticks(positions, labels)
    for tick, point in zip(ax.get_yticklabels(), points):
        tick.set_fontsize(10)
        if (point[0], point[1], point[2]) in front_ids:
            tick.set_fontweight("bold")
    span = max(values) / min(values)
    use_log = span >= 12
    if use_log:
        ax.set_xscale("log")
        ax.set_xlim(min(values) / 1.6, max(values) * 2.4)
        xlabel = "decompression MB/s   (log, faster →)"
    else:
        ax.set_xlim(0, max(values) * 1.18)
        xlabel = "decompression MB/s   (faster →)"
    for y, value in zip(positions, values):
        label = f"{value:.1f}"
        if use_log:
            ax.text(value * 1.04, y, label, va="center", ha="left", fontsize=8.5, color="#222")
        else:
            ax.text(value + max(values) * 0.012, y, label, va="center", ha="left", fontsize=8.5, color="#222")
    ax.set_xlabel(xlabel)
    ax.set_title(title)
    ax.grid(axis="x", ls=":", color="#d0d7de", zorder=0)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    fig.tight_layout()
    _save(fig, path)
    return None if omitted is None else omitted[2]


def md_table(rows: list[list[str]], columns: list[dict], active: int, link_names: list[str]) -> str:
    head = []
    for col, target in zip(columns, link_names):
        if col["index"] == active:
            head.append(f"**{col['header']}**")
        else:
            head.append(f"[{col['header']}]({target})")
    sep = []
    for col in columns:
        sep.append("---:" if not col["textual"] and not col["dcat"] else ":---")
    body = ["|" + "|".join(row) + "|" for row in rows]
    return "\n".join([
        "|" + "|".join(head) + "|",
        "|" + "|".join(sep) + "|",
        *body,
    ])


def graph_section(scatter_rel: str, bars_rel: str, scatter_cap: str, bars_cap: str) -> str:
    return "\n".join([
        "",
        f"![Compression and decompression speed versus ratio]({scatter_rel})",
        "",
        scatter_cap,
        "",
        f"![Decompression speed]({bars_rel})",
        "",
        bars_cap,
        "",
    ])


def build(
    blocks,
    epilogue,
    chart_dir: Path,
    chart_rel: str,
    stem: str,
    out_dir: Path,
) -> list[Path]:
    written: list[Path] = []
    multi = len(blocks) > 1
    epi = "\n".join(epilogue).strip("\n")

    for number, (preamble, header, rows) in enumerate(blocks, start=1):
        prefix = block_prefix(number, multi)
        columns = column_meta(header, rows)
        default_i = find_col(header, ("c size",))
        if default_i is None:
            default_i = 0
        links = column_view_links(stem, prefix, columns)
        title = section_title(preamble)
        chart_tag = f"{prefix}{stem}" if prefix else stem
        scatter_name = f"{chart_tag}_speed_vs_ratio.png"
        bars_name = f"{chart_tag}_decomp_speed.png"
        omitted = write_scatter(chart_dir / scatter_name, title, rows, header)
        write_bars(chart_dir / bars_name, "Decompression speed", rows, header)
        scatter_rel = f"{chart_rel}/{scatter_name}" if chart_rel else scatter_name
        bars_rel = f"{chart_rel}/{bars_name}" if chart_rel else bars_name
        omit_note = f" {omitted} is omitted so the scale stays readable." if omitted else ""
        scatter_cap = (
            "Each point is one codec level. Color is the codec family. "
            "The line is the Pareto front (nothing else is both smaller and faster) and only that front is labeled. "
            "Every codec is named on the bar chart."
            + omit_note
        )
        bars_cap = (
            "Fastest decompression at the top. The ratio is next to the name. "
            "Bold names are on the decompression Pareto front."
            + omit_note
        )
        graphs = graph_section(scatter_rel, bars_rel, scatter_cap, bars_cap)
        preamble_text = "\n".join(preamble).strip("\n")

        for col in columns:
            active = col["index"]
            ordered = rows if active == default_i else sort_rows(rows, col)
            parts = [_GEN_MARKER, ""]
            if preamble_text:
                parts.append(preamble_text)
                parts.append("")
            parts.append(md_table(ordered, columns, active, links))
            parts.append(graphs.rstrip())
            if epi and number == len(blocks):
                parts.append("")
                parts.append(epi)
            content = "\n".join(parts).rstrip() + "\n"
            path = out_dir / view_basename(stem, prefix, col["header"])
            path.write_text(content, encoding="utf-8")
            written.append(path)

        name_i = find_col(header, ("name",))
        bits = []
        for col in columns:
            active = col["index"]
            ordered = rows if active == default_i else sort_rows(rows, col)
            if not ordered:
                continue
            shown = plain(ordered[0][col["index"]])
            who = plain(ordered[0][name_i]) if name_i is not None else ""
            bits.append(f"{col['header']}: {shown} ({who})")
        print(f"block {number}: {len(rows)} rows → {len(columns)} views — " + "; ".join(bits))

    return written


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Write one Markdown page per table sort (column headers link across pages).",
    )
    parser.add_argument(
        "markdown",
        type=Path,
        help="TurboBench -p4 Markdown (e.g. data.md); not the enhanced micro.md views",
    )
    parser.add_argument(
        "--stem",
        type=str,
        metavar="NAME",
        help="base name for outputs (default: input filename without extension, e.g. micro)",
    )
    parser.add_argument(
        "--out-dir", type=Path,
        help="directory for .md views (default: same folder as the source file)",
    )
    parser.add_argument("--charts", type=Path, help="PNG output directory (default: <out-dir>/charts)")
    args = parser.parse_args()

    source = args.markdown.resolve()
    if not source.is_file():
        print(f"not found: {source}", file=sys.stderr)
        return 1
    text = strip_bench_views_artifacts(source.read_text(encoding="utf-8"))
    blocks, epilogue = parse_blocks(text)
    if not blocks:
        print(f"no Markdown table in {source}", file=sys.stderr)
        return 1
    stem = (args.stem or source.stem).strip()
    if not stem:
        print("empty --stem / input name", file=sys.stderr)
        return 1
    out_dir = (args.out_dir or source.parent).resolve()
    chart_dir = (args.charts or out_dir / "charts").resolve()
    try:
        chart_rel = chart_dir.relative_to(out_dir).as_posix()
    except ValueError:
        chart_rel = chart_dir.as_posix()

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({
        "font.size": 11,
        "axes.titlesize": 13,
        "axes.titleweight": "bold",
        "axes.labelsize": 11,
        "figure.facecolor": "white",
        "axes.facecolor": "white",
        "savefig.facecolor": "white",
    })

    written = build(blocks, epilogue, chart_dir, chart_rel, stem, out_dir)
    print(f"stem={stem} charts in {chart_dir}")
    for path in written:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
